# Build everything a release ships for one target from an already-built static binary: the
# .deb, the .rpm, the tarball and the checksums.
#
#   cargo build --release --locked --target x86_64-unknown-linux-musl -p snapall
#   packaging/build-packages.sh x86_64-unknown-linux-musl
#
# Needs: cargo-deb, cargo-generate-rpm, python3, GNU tar. Output goes to dist/. CI and the
# release workflow both call this, so the files that are tested are the files that ship.
#
# The shell completions and the man page are generated by the binary itself, from the contract it
# is built with (`snapall completions SHELL`, `snapall man`), so this must run on the architecture
# the binary was built for: CI and the release both build natively on each architecture.
#
# Everything is reproducible: every timestamp is the commit's (SOURCE_DATE_EPOCH), tar entries are
# sorted and owned by root, and gzip does not record a name or time.
set -euo pipefail

target="${1:?usage: $0 <rust target triple, e.g. x86_64-unknown-linux-musl>}"
cd "$(dirname "$0")/.."

binary="target/$target/release/snapall"
if [ ! -x "$binary" ]; then
  echo "missing $binary; build it first:" >&2
  echo "  cargo build --release --locked --target $target -p snapall" >&2
  exit 1
fi
version="$("$binary" --version 2>/dev/null | awk '{print $2}')" || version=""
if [ -z "$version" ]; then
  echo "cannot run $binary: it generates its own completions and man page, so build on its architecture" >&2
  exit 1
fi

SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-$(git log -1 --format=%ct 2>/dev/null || date +%s)}"
export SOURCE_DATE_EPOCH

generated=packaging/generated
rm -rf "$generated" dist
mkdir -p "$generated" dist
"$binary" completions bash > "$generated/snapall.bash"
"$binary" completions zsh > "$generated/_snapall"
"$binary" completions fish > "$generated/snapall.fish"
"$binary" completions nushell > "$generated/snapall.nu"
"$binary" man | gzip -9n > "$generated/snapall.1.gz"

# The binary contains MIT/Apache/... libraries whose notices must travel with it.
python3 packaging/third-party-licenses.py "$target"
cargo deb --no-build --package snapall --target "$target" --output dist/
cargo generate-rpm --package crates/snapall --target "$target" --output dist/

# The tarball, for distributions that package nothing (Alpine, Void, ...): the static binary, the
# license and notices, the completions, the man page and the launcher entry with its icon, under
# one top-level directory.
name="snapall-v$version-$target"
stage="$(mktemp -d)"
mkdir -p "$stage/$name/completions" "$stage/$name/man" "$stage/$name/desktop" "$stage/$name/filemanagers"
cp "$binary" LICENSE README.md THIRD-PARTY-LICENSES.md "$stage/$name/"
cp "$generated/snapall.bash" "$generated/_snapall" "$generated/snapall.fish" "$generated/snapall.nu" "$stage/$name/completions/"
cp "$generated/snapall.1.gz" "$stage/$name/man/"
cp packaging/desktop/snapall.desktop packaging/desktop/snapall.svg "$stage/$name/desktop/"
cp packaging/filemanagers/* "$stage/$name/filemanagers/"
tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="@$SOURCE_DATE_EPOCH" \
  -C "$stage" -cf - "$name" | gzip -9n > "dist/$name.tar.gz"
rm -rf "$stage"

# The bare binary stays in dist/ for the distro tests; it is not a release asset.
cp "$binary" "dist/snapall-$target"

# Checksums only for what is published (the tarball, .deb and .rpm), so `sha256sum -c` works for
# whoever downloads them.
(cd dist && sha256sum -- "$name.tar.gz" *.deb *.rpm > SHA256SUMS)
echo "built:" && ls -l dist
